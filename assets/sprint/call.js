/* Scoping Call page: Cal.com inline embed with the scorecard result prefilled.

   The scorecard links here as /call/?workflow=...&score=...&gaps=... Those
   three values go into the embed's config, which Cal.com appends to the
   booking page URL; a URL parameter prefills the booking question whose
   identifier matches it. The event type needs questions with the identifiers
   workflow, score, and gaps. */
(function () {
  var mount = document.getElementById('cal-inline');
  if (!mount) return;

  var PREFILL_KEYS = ['workflow', 'score', 'gaps'];
  var CAL_ORIGIN = 'https://app.cal.com';

  var direct = document.getElementById('cal-direct');
  var params = new URLSearchParams(window.location.search);
  var prefill = {};
  PREFILL_KEYS.forEach(function (k) {
    var v = params.get(k);
    if (v) prefill[k] = v.slice(0, 1000);
  });

  // Arriving from the scorecard: say the result travels with the booking,
  // and drop the "score it first" nudge.
  if (prefill.score) {
    document.getElementById('call-prefill-score').textContent = prefill.score;
    document.getElementById('call-prefill').hidden = false;
    document.getElementById('call-nudge').hidden = true;
  }

  function withPrefill(url) {
    var u = new URL(url);
    PREFILL_KEYS.forEach(function (k) {
      if (prefill[k]) u.searchParams.set(k, prefill[k]);
    });
    return u.toString();
  }

  function track(event) {
    window.dataLayer = window.dataLayer || [];
    window.dataLayer.push({ event: event });
  }

  function start(bookingUrl, thanksUrl) {
    direct.href = withPrefill(bookingUrl);
    var calLink = new URL(bookingUrl).pathname.replace(/^\/+|\/+$/g, '');
    var ns = calLink.split('/').pop();

    // Cal.com's embed loader, as generated by its Embed Snippet Generator.
    (function (C, A, L) { var p = function (a, ar) { a.q.push(ar); }; var d = C.document; C.Cal = C.Cal || function () { var cal = C.Cal; var ar = arguments; if (!cal.loaded) { cal.ns = {}; cal.q = cal.q || []; d.head.appendChild(d.createElement('script')).src = A; cal.loaded = true; } if (ar[0] === L) { var api = function () { p(api, arguments); }; var namespace = ar[1]; api.q = api.q || []; if (typeof namespace === 'string') { cal.ns[namespace] = cal.ns[namespace] || api; p(cal.ns[namespace], ar); p(cal, ['initNamespace', namespace]); } else p(cal, ar); return; } p(cal, ar); }; })(window, CAL_ORIGIN + '/embed/embed.js', 'init');

    var Cal = window.Cal;
    Cal('init', ns, { origin: CAL_ORIGIN });
    Cal.ns[ns]('inline', {
      elementOrSelector: '#cal-inline',
      calLink: calLink,
      config: Object.assign({ layout: 'month_view', theme: 'dark' }, prefill)
    });
    Cal.ns[ns]('ui', {
      theme: 'dark',
      layout: 'month_view',
      hideEventTypeDetails: false,
      cssVarsPerTheme: { dark: { 'cal-brand': '#c89a3e' } }
    });
    Cal.ns[ns]('on', {
      action: 'bookingSuccessfulV2',
      callback: function () {
        track('scoping_call_booked');
        if (thanksUrl) window.location.href = thanksUrl;
      }
    });
  }

  window.Sprint.load().then(function (cfg) {
    start(cfg.urls.booking, cfg.urls.thanks);
  }, function () {
    // Config unavailable: the static link still points at the booking page.
    start(direct.getAttribute('href'), '');
  });
})();
